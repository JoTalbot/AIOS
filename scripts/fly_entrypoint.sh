#!/bin/bash
echo "🌌 Запуск AIOS v22.0.0 на глобальной инфраструктуре Fly.io..."

# 1. Стартуем P2P-ноду AIOS на 8000 порту (обрабатывает входящий трафик Fly.io)
echo "🚀 Поднятие P2P-узла..."
uvicorn aios_core.p2p_network:app --host 0.0.0.0 --port 8000 &

# 2. Бесконечный автономный цикл "AI CEO" в фоновом режиме
echo "💼 Инициализация фонового коммерческого контура..."
while true; do
    echo "[$(date)] Запуск коммерческого сканирования (Lead Generation)..."
    python3 scripts/run_commercial_pipeline.py
    
    # После завершения засыпаем на 1 час (3600 секунд) перед новым поиском
    echo "💤 Цикл завершен. Ожидание 1 час перед следующим сканированием..."
    sleep 3600
done
